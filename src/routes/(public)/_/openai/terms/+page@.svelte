  <h1>Pocketrides Monetization Policy</h1>
  <p>The following is a list of speech that will NOT be monetized on Pocketrides.</p>
  <h2>Hate speech</h2>
  <ul>
    <li>
      Content that partakes, encourages, or promotes violence or physical harm
      against one's person or property.
    </li>
    <li>
      Content that engages in, alludes to, encourages, or promotes hate or violence
      toward any group based on race, religion, disability, gender identity, gender,
      sexual orientation, national origin or any other immutable characteristic.
    </li>
  </ul>
  <h2>Illegal products or services</h2>
  <ul>
    <li>
      Illegal drugs, substances to mimic illegal drugs, or equipment used to make
      illegal drugs
    </li>
    <li>Fake ID or Fake Reference providing services</li>
    <li>Telecommunication manipulation equipment</li>
    <li>
      Any other products or services that are unlawful in the jurisdictions where you
      are located
    </li>
  </ul>
  <h2>Infringing intellectual property rights</h2>
  <ul>
    <li>
      Any sales or distribution of music, movies, software, or any other licensed
      materials without appropriate authorization
    </li>
    <li>Counterfeit goods; illegally imported or exported products</li>
    <li>Unauthorized sale of brand name or designer products or services</li>
    <li>
      Any other products or services that directly infringe or facilitate
      infringement upon the trademark, patent, copyright, trade secrets, proprietary
      or privacy rights of any third party
    </li>
  </ul>
  <h2>Products and services that are unfair, predatory, or deceptive</h2>
  <ul>
    <li>Pyramid schemes</li>
    <li>
      ‘Get rich quick’ schemes including: investment opportunities or other services
      that promise high rewards to mislead consumers; schemes that claim to offer
      high rewards for very little effort or up front work; sites that promise fast
      and easy money; businesses that make outrageous claims, use deceptive
      testimonials, use high-pressure upselling, and/or use fake testimonials; (with
      or without a written contract) offering unrealistic incentives/rewards as an
      inducement to purchase products or services but do not respond to any queries
      after the purchase
    </li>
    <li>
      No value added services including sale or resale of a service without added
      benefit to the buyer and resale of government offerings without authorization
      or added value
    </li>
    <li>Sales of online traffic or engagement</li>
    <li>Negative response marketing and telemarketing</li>
    <li>
      Predatory mortgage consulting, lending, credit repair and counseling services
    </li>
    <li>Predatory investment opportunities with no or low money down</li>
    <li>
      Remote technical support; mugshot publication or pay-to-remove sites; essay
      mills; chain letters; door-to-door sales
    </li>
  </ul>
  <h2>Adult content and services</h2>
  <ul>
    <li>
      Pornography and other mature audience content (including literature, imagery
      and other media) depicting nudity or explicit sexual acts
    </li>
    <li>
      Adult services including prostitution, escorts, pay-per view, sexual massages,
      and adult live chat features
    </li>
    <li>Adult video stores</li>
    <li>Gentleman's clubs, topless bars, and strip clubs</li>
  </ul>
  <h2>Certain legal services</h2>
  <ul>
    <li>
      Law firms collecting funds for purposes other than legal service fee payment
    </li>
    <li>Bankruptcy attorneys</li>
    <li>Bail bonds</li>
  </ul>
  <h2>Firearms, explosives and dangerous materials</h2>
  <ul>
    <li>Guns, gunpowders, ammunitions, weapons, fireworks and other explosives</li>
    <li>
      Peptides, research chemicals, and other toxic, flammable and radioactive
      materials
    </li>
  </ul>
  <h2>Gambling</h2>
  <ul>
    <li>
      Games of chance including gambling, internet gambling, sweepstakes and
      contests, fantasy sports leagues with for a monetary or material prize
    </li>
    <li>Sports forecasting or odds making with a monetary or material prize</li>
    <li>Lotteries</li>
    <li>Bidding fee auctions</li>
  </ul>
  <h2>Marijuana</h2>
  <ul>
    <li>Cannabis products</li>
    <li>Cannabis dispensaries and related businesses</li>
    <li>Products containing any amount of CBD/THC</li>
  </ul>
  <h2>Political Speech and Content</h2>
  <ul>
    <li>Campaigns for any kind of elected office</li>
    <li>Political speech for or against any one candidate or political party</li>
    <li>
      Posts that may condone or imply committing acts of violence on behalf of a
      politician or political party
    </li>
  </ul>
  <h2>Additional Restricted Activities</h2>
